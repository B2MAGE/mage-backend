CREATE TABLE builder_templates (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    name VARCHAR(100) NOT NULL CHECK (length(trim(name)) BETWEEN 1 AND 100),
    scene_data JSONB NOT NULL CHECK (scene_data->>'kind' = 'builder'),
    thumbnail_ref VARCHAR(512),
    revision BIGINT NOT NULL DEFAULT 0 CHECK (revision >= 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX builder_templates_owner_name ON builder_templates(owner_user_id, lower(name));

-- Presigned uploads are single-use and never become scene-owned assets.
CREATE TABLE builder_template_uploads (
    object_key VARCHAR(512) PRIMARY KEY,
    owner_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    expires_at TIMESTAMPTZ NOT NULL,
    consumed BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE TABLE builder_template_asset_cleanup (
    thumbnail_ref VARCHAR(512) PRIMARY KEY,
    not_before TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
